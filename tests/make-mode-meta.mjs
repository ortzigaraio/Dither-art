// Writes src/modes/meta.js: the plain-data part of every mode (id, category, name, blurb, badges, GPU surface)
// that the app needs before a mode's code is loaded (mode list, gallery, share-link validation). The modes
// themselves are loaded on demand by src/modes/registry.js. Re-run after adding a mode or changing its name,
// blurb, badges or surface: `cd tests && node make-mode-meta.mjs` (perf.spec.js fails when meta.js is stale).
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { repoRoot } from './module-graph.mjs';

export async function modeMeta() {
  const { MODES } = await import(resolve(repoRoot, 'src/modes/index.js'));
  return MODES.map((m) => ({
    id: m.id,
    category: m.category,
    name: m.name,
    blurb: m.blurb,
    badges: m.badges || [],
    surface: m.surface === 'gl' ? 'gl' : '2d',
  }));
}

export function metaSource(meta) {
  const rows = meta.map((m) => `  ${JSON.stringify(m)},`).join('\n');
  return `// Generated by tests/make-mode-meta.mjs from the mode modules: do not edit by hand.
// Plain data of every mode, in the order of the UI. The code of a mode is loaded on demand (registry.js).
export const MODE_META = Object.freeze([
${rows}
].map((m) => Object.freeze(m)));
`;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(repoRoot, 'tests/make-mode-meta.mjs')) {
  const meta = await modeMeta();
  writeFileSync(resolve(repoRoot, 'src/modes/meta.js'), metaSource(meta));
  console.log('src/modes/meta.js:', meta.length, 'modes');
}
